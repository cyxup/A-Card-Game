function interpolate(text: string, vars?: Vars): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key: string) =>
    vars[key] === undefined ? match : String(vars[key]),
  );
}

export function translate(text: string, vars?: Vars, locale: Locale = getPrefs().locale): string {
  const template = locale === "fr" ? (FR[text] ?? text) : text;
  return interpolate(template, vars);
}

/** Non-hook version for formatters. Components using it should also subscribe to prefs. */
export function tNow(text: string, vars?: Vars): string {
  return translate(text, vars, getPrefs().locale);
}

export function useT(): (text: string, vars?: Vars) => string {
  const { locale } = usePrefs();
  return (text, vars) => translate(text, vars, locale);
}

export function useLocale(): Locale {
  return usePrefs().locale;
}

